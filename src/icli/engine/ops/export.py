BADADDR = ida_idaapi.BADADDR

KERNEL_FORMATS = {"asm": ida_loader.OFILE_ASM, "lst": ida_loader.OFILE_LST, "html": ida_loader.OFILE_LST,
                  "map": ida_loader.OFILE_MAP, "idc": ida_loader.OFILE_IDC, "dif": ida_loader.OFILE_DIF}


def _bounds(ctx: Ctx, selectors: list[dict] | None) -> tuple[int, int]:
    if not selectors:
        return ida_ida.inf_get_min_ea(), ida_ida.inf_get_max_ea()
    sp = spans(select.evaluate(ctx, selectors))
    if not sp:
        raise IcliError(Exit.EMPTY_SELECTION, "selector matched nothing", "NOMATCH")
    return min(s for s, _ in sp), max(e for _, e in sp)


def _kernel_file(ctx: Ctx, fmt: str, path: str, ea1: int, ea2: int, flags: int) -> None:
    f = ida_fpro.qfile_t()
    if not f.open(path, "wb"):
        raise IcliError(Exit.NOT_FOUND, f"{path}: cannot write", "NOTFOUND")
    try:
        if fmt == "exe":
            n = ida_loader.gen_exe_file(f.get_fp())
        else:
            n = ida_loader.gen_file(KERNEL_FORMATS[fmt], f.get_fp(), ea1, ea2, flags)
    finally:
        f.close()
    if n is not None and n < 0:
        raise IcliError(Exit.LOAD, f"export {fmt}: the kernel could not generate this format", "EXPORT")


def _write(path: str, data: str | bytes) -> int:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        data = data.encode("utf-8")
    p.write_bytes(data)
    return len(data)


def _functions(ctx: Ctx, selectors: list[dict] | None) -> list:
    fk = KINDS["function"]
    if selectors:
        return list(select.functions_of(ctx, select.evaluate(ctx, selectors)))
    out = []
    for it in fk.all(ctx):
        seg = ida_segment.getseg(it.ea)
        if seg is not None and seg.type in (ida_segment.SEG_XTRN, ida_segment.SEG_IMP):
            continue
        if fk.get(it, "lib", ctx):
            continue
        out.append(it)
    return out


def _pseudocode_unit(ctx: Ctx, funcs: list, with_types: bool = True) -> tuple[str, int]:
    from .decompile import referenced_types

    decomp.require()
    bodies = []
    failed = 0
    for fi in funcs:
        r = decomp.decompile(fi.ea)
        if r.ok:
            bodies.append(f"//----- ({fi.ea:016X}) ----------------------------------------------------\n{r.text}\n")
        else:
            failed += 1
            bodies.append(f"// {ida_funcs.get_func_name(fi.ea)} @ {fi.ea:#x}: decompilation failed: {r.message}\n")
    text = "\n".join(bodies)
    header = ""
    if with_types:
        decls = referenced_types(text)
        protos = []
        for fi in funcs:
            for c in callees(fi.obj):
                p = typesupport.prototype(c)
                if p:
                    protos.append(p + ";")
        header = "\n\n".join(d for _, d in decls)
        if protos:
            header += "\n\n// callee prototypes\n" + "\n".join(dict.fromkeys(protos))
        header = (header + "\n\n") if header.strip() else ""
    return header + text, failed


def _patched_input(path: str, in_place: bool) -> tuple[str, dict]:
    """The input file with every patched byte written at its file offset
    (works for any file format, unlike the kernel's EXE generator)."""
    src = ida_nalt.get_input_file_path()
    if not src or not Path(src).is_file():
        raise IcliError(Exit.NOT_FOUND, f"input file {src or '?'} is not available to rebuild", "NOTFOUND")
    data = bytearray(Path(src).read_bytes())
    applied = skipped = 0

    def visit(ea: int, fpos: int, org: int, val: int) -> int:
        nonlocal applied, skipped
        if fpos is None or fpos < 0 or fpos >= len(data):
            skipped += 1
        else:
            data[fpos] = val & 0xFF
            applied += 1
        return 0

    ida_bytes.visit_patched_bytes(0, BADADDR, visit)
    target = src if in_place else path
    _write(target, bytes(data))
    return target, {"patched_bytes": applied, "not_file_backed": skipped, "in_place": in_place}


def _python_script() -> str:
    """IDAPython recreating user annotations: names, comments, user types."""
    lines = ["# generated by icli export python", "import ida_bytes, ida_name, ida_typeinf, ida_funcs, idc", "",
             "def T(ea, decl):", "    idc.SetType(ea, decl)", ""]
    for i in range(ida_name.get_nlist_size()):
        ea = ida_name.get_nlist_ea(i)
        fl = ida_bytes.get_flags(ea)
        if ida_bytes.has_user_name(fl):
            lines.append(f"ida_name.set_name({ea:#x}, {ida_name.get_nlist_name(i)!r}, ida_name.SN_NOWARN)")
    for s in range(ida_segment.get_segm_qty()):
        seg = ida_segment.getnseg(s)
        ea = seg.start_ea
        while ea != BADADDR and ea < seg.end_ea:
            fl = ida_bytes.get_flags(ea)
            if ida_bytes.has_cmt(fl):
                for rep in (False, True):
                    c = ida_bytes.get_cmt(ea, rep)
                    if c:
                        lines.append(f"ida_bytes.set_cmt({ea:#x}, {c!r}, {rep})")
            if ida_nalt.is_userti(ea):
                t = typesupport.prototype(ea) or typesupport.type_at(ea)
                if t:
                    lines.append(f"T({ea:#x}, {t + ';'!r})")
            ea = ida_bytes.next_head(ea, seg.end_ea)
    for _, name, tif in typesupport.local_types():
        lines.append(f"ida_typeinf.parse_decls(None, {typesupport.type_definition(tif, name)!r}, None, "
                     "ida_typeinf.HTI_DCL)")
    return "\n".join(lines) + "\n"


def _sarif(ctx: Ctx, selectors: list[dict] | None) -> str:
    sel = select.evaluate(ctx, selectors) if selectors else select.Selection()
    input_path = ida_nalt.get_input_file_path() or ida_nalt.get_root_filename()
    results = []
    for it in sel:
        if not isinstance(it.ea, int):
            continue
        name = it.kind.get(it, "name", ctx) or f"{it.ea:#x}"
        off = ida_loader.get_fileregion_offset(it.ea)
        loc: dict[str, Any] = {
            "logicalLocations": [{"name": name, "kind": "function" if it.kind.name == "function" else "member",
                                  "fullyQualifiedName": f"{name}@{it.ea:#x}"}],
        }
        if off is not None and off >= 0:
            loc["physicalLocation"] = {"artifactLocation": {"uri": Path(input_path).as_uri() if input_path else ""},
                                       "region": {"byteOffset": int(off),
                                                  "byteLength": int(it.kind.get(it, "size", ctx) or 1)}}
        results.append({"ruleId": "icli.selection", "level": "note",
                        "message": {"text": f"{it.kind.record} {name} at {it.ea:#x}"}, "locations": [loc],
                        "properties": {"ea": f"{it.ea:#x}", "kind": it.kind.record}})
    doc = {"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
           "runs": [{"tool": {"driver": {"name": "icli", "informationUri": "https://hex-rays.com",
                                         "rules": [{"id": "icli.selection",
                                                    "shortDescription": {"text": "Item selected by an icli selector"}}]}},
                     "artifacts": [{"location": {"uri": Path(input_path).as_uri() if input_path else ""}}],
                     "results": results}]}
    return json.dumps(doc, indent=2) + "\n"


def _graph(ctx: Ctx, selectors: list[dict] | None, kind: str) -> tuple[list[dict], list[dict], str]:
    funcs = _functions(ctx, selectors)
    nodes: dict[str, dict] = {}
    edges: list[dict] = []

    def nm(ea: int) -> str:
        return ida_name.get_name(ea) or f"{ea:#x}"

    if kind == "calls":
        for fi in funcs:
            nodes.setdefault(nm(fi.ea), {"id": nm(fi.ea), "label": nm(fi.ea)})
            for c in callees(fi.obj):
                nodes.setdefault(nm(c), {"id": nm(c), "label": nm(c)})
                edges.append({"src": nm(fi.ea), "dst": nm(c)})
    elif kind == "flow":
        import ida_gdl

        from .. import listing

        for fi in funcs:
            for b in ida_gdl.FlowChart(fi.obj, flags=ida_gdl.FC_PREDS):
                bid = f"{b.start_ea:#x}"
                from ..kinds.base import iter_heads

                label = "\n".join(f"{ea:#x}: {listing.instruction_text(ea)}" for ea in iter_heads(b.start_ea, b.end_ea))
                nodes[bid] = {"id": bid, "label": label}
                for s in b.succs():
                    edges.append({"src": bid, "dst": f"{s.start_ea:#x}"})
    elif kind == "xrefs":
        import ida_xref

        for fi in funcs:
            nodes.setdefault(nm(fi.ea), {"id": nm(fi.ea), "label": nm(fi.ea)})
            xb = ida_xref.xrefblk_t()
            ok = xb.first_to(fi.ea, ida_xref.XREF_NOFLOW)
            while ok:
                f = ida_funcs.get_func(xb.frm)
                src = nm(f.start_ea) if f else nm(xb.frm)
                nodes.setdefault(src, {"id": src, "label": src})
                edges.append({"src": src, "dst": nm(fi.ea)})
                ok = xb.next_to()
    else:
        raise IcliError(Exit.USAGE, f"--graph {kind}: one of calls, flow, xrefs", "USAGE")
    return list(nodes.values()), edges, f"{kind} graph"


def _per_item(ctx: Ctx, items: list, path_template: str, render: Callable[[Any], str | bytes]) -> list[dict]:
    out = []
    for it in items:
        path = tmpl.render_path(path_template, {f: it.kind.get(it, f, ctx) for f in tmpl.parse(
            path_template, record_newline=False).fields})
        n = _write(path, render(it))
        out.append({"_t": "export", "path": os.path.abspath(path), "size": n, "ea": A(it.ea),
                    "name": it.kind.get(it, "name", ctx)})
    return out


@op("export")
def export(ctx: Ctx, format: str, path: str | None = None, selectors: list[dict] | None = None,
           path_template: str | None = None, with_types: bool = False, maturity: str = "lvars",
           graph: str = "calls", segments: bool = False, demangle: bool = False, locals: bool = False,
           highlight: list[int] | None = None, in_place: bool = False) -> list[dict]:
    fmt = format
    tmp = None
    if path is None and path_template is None:
        fd, tmp = tempfile.mkstemp(prefix="icli-export-")
        os.close(fd)
        path = tmp
    try:
        recs = _export(ctx, fmt, path, selectors, path_template, with_types, maturity, graph, segments, demangle,
                       locals, highlight or [], in_place)
        if tmp is not None:
            data = Path(tmp).read_bytes()
            try:
                ctx.raw.append(data.decode("utf-8"))
            except UnicodeDecodeError:
                ctx.extra["binary"] = data.hex()
            return []
        return recs
    finally:
        if tmp is not None:
            Path(tmp).unlink(missing_ok=True)


def _export(ctx: Ctx, fmt: str, path: str | None, selectors: list[dict] | None, path_template: str | None,
            with_types: bool, maturity: str, graph: str, segments: bool, demangle: bool, locals: bool,
            highlight: list[int], in_place: bool) -> list[dict]:
    def done(p: str, **extra: Any) -> list[dict]:
        return [{"_t": "export", "format": fmt, "path": os.path.abspath(p), "size": Path(p).stat().st_size, **extra}]

    if fmt in ("asm", "lst", "html") and path_template:
        funcs = _functions(ctx, selectors)

        def render(it: Any) -> bytes:
            fd, t = tempfile.mkstemp()
            os.close(fd)
            s, e = chunks(it.obj)[0]
            _kernel_file(ctx, fmt, t, s, e, ida_loader.GENFLG_GENHTML if fmt == "html" else 0)
            data = Path(t).read_bytes()
            os.unlink(t)
            return data

        return _per_item(ctx, funcs, path_template, render)
    if fmt in ("asm", "lst", "html", "map", "idc", "dif"):
        ea1, ea2 = _bounds(ctx, selectors) if fmt in ("asm", "lst", "html") else (
            ida_ida.inf_get_min_ea(), ida_ida.inf_get_max_ea())
        flags = 0
        if fmt == "html":
            flags |= ida_loader.GENFLG_GENHTML
        if fmt == "asm" and with_types:
            flags |= ida_loader.GENFLG_ASMTYPE
        if fmt == "map":
            flags |= (ida_loader.GENFLG_MAPSEG if segments else 0) | ida_loader.GENFLG_MAPNAME | (
                ida_loader.GENFLG_MAPDMNG if demangle else 0) | (ida_loader.GENFLG_MAPLOC if locals else 0)
        if fmt == "idc":
            flags |= ida_loader.GENFLG_IDCTYPE
        saved: dict[int, int] = {}
        for ea in highlight:
            saved[ea] = ida_nalt.get_item_color(ea)
            ida_nalt.set_item_color(ea, 0xC0FFC0)
        try:
            _kernel_file(ctx, fmt, path, ea1, ea2, flags)
        finally:
            for ea, c in saved.items():
                if c == 0xFFFFFFFF:
                    ida_nalt.del_item_color(ea)
                else:
                    ida_nalt.set_item_color(ea, c)
        return done(path)
    if fmt == "exe":
        target, info = _patched_input(path, in_place)
        return done(target, **info)
    if fmt == "python":
        _write(path, _python_script())
        return done(path)
    if fmt == "journal":
        _write(path, "".join(json.dumps({"_t": "journal", **r}, separators=(",", ":")) + "\n"
                             for r in journal.records()))
        return done(path, records=journal.length())
    if fmt == "bin":
        sp = spans(select.evaluate(ctx, selectors)) if selectors else [
            (ida_segment.getnseg(i).start_ea, ida_segment.getnseg(i).end_ea) for i in range(ida_segment.get_segm_qty())]
        data = b"".join(ida_bytes.get_bytes(s, e - s) or b"" for s, e in sp)
        _write(path, data)
        return done(path, ranges=[{"start": A(s), "end": A(e)} for s, e in sp])
    if fmt in ("c", "cpp"):
        funcs = _functions(ctx, selectors)
        if path_template:
            return _per_item(ctx, funcs, path_template, lambda it: _pseudocode_unit(ctx, [it], True)[0])
        text, failed = _pseudocode_unit(ctx, funcs, True)
        if fmt == "cpp":
            text = "// C++ view: Hex-Rays pseudocode with member functions named Class::method\n" + text
        _write(path, text)
        if failed:
            ctx.set_status(Exit.PARTIAL)
        return done(path, functions=len(funcs), failed=failed)
    if fmt == "mc":
        funcs = _functions(ctx, selectors)
        if path_template:
            return _per_item(ctx, funcs, path_template,
                             lambda it: f"// {ida_funcs.get_func_name(it.ea)} at {maturity}\n"
                                        f"{decomp.microcode(it.ea, maturity)}\n")
        text = "\n\n".join(f"// {ida_funcs.get_func_name(fi.ea)} @ {fi.ea:#x} ({maturity})\n"
                           f"{decomp.microcode(fi.ea, maturity)}" for fi in funcs) + "\n"
        _write(path, text)
        return done(path, functions=len(funcs))
    if fmt == "h":
        from .edit_code import type_dump

        _write(path, type_dump(ctx, None)[0]["text"])
        return done(path)
    if fmt == "til":
        from .knowledge import til_export

        til_export(ctx, path)
        return done(path)
    if fmt == "pat":
        from .knowledge import sig_patterns

        _write(path, sig_patterns(ctx, selectors)[0]["text"])
        return done(path)
    if fmt in ("dot", "gdl", "svg"):
        nodes, edges, name = _graph(ctx, selectors, graph)
        text = lgraph.render(nodes, edges, "gdl" if fmt == "gdl" else "dot", name)
        if fmt == "svg":
            text = lgraph.to_svg(text)
        _write(path, text)
        return done(path, nodes=len(nodes), edges=len(edges))
    if fmt == "sarif":
        _write(path, _sarif(ctx, selectors))
        return done(path)
    raise IcliError(Exit.USAGE, f"export format {fmt!r} is handled by the client", "USAGE")


