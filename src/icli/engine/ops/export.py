@op("export.minimal")
def export_minimal(ctx: Ctx, selectors: list[dict]) -> dict:
    """What a self-contained reproducer needs: the selected functions'
    bytes, their callees' prototypes, and the local types they use."""
    from .decompile import referenced_types

    funcs = list(select.functions_of(ctx, select.evaluate(ctx, selectors)))
    if not funcs:
        raise IcliError(Exit.EMPTY_SELECTION, "selection contains no function", "NOMATCH")
    seg_bits = 64 if ida_ida.inf_is_64bit() else 32
    regions, functions, names = [], [], []
    for fi in funcs:
        for s, e in chunks(fi.obj):
            regions.append({"start": s, "end": e, "bytes": (ida_bytes.get_bytes(s, e - s) or b"").hex()})
        functions.append({"start": fi.ea, "end": fi.obj.end_ea, "name": ida_funcs.get_func_name(fi.ea),
                          "type": typesupport.prototype(fi.ea) if typesupport.tinfo_at(fi.ea) else None})
        for c in callees(fi.obj):
            if c in {f.ea for f in funcs}:
                continue
            names.append({"ea": c, "name": ida_name.get_name(c), "type": typesupport.prototype(c)})
    text = "\n".join(decomp.decompile(fi.ea).text for fi in funcs if decomp.available() and decomp.decompile(fi.ea).ok)
    types = [d for _, d in referenced_types(text + "\n" + "\n".join(f["type"] or "" for f in functions))]
    return {"_t": "minimal", "processor": ida_ida.inf_get_procname(), "bitness": seg_bits,
            "big_endian": bool(ida_ida.inf_is_be()), "regions": regions, "functions": functions, "names": names,
            "types": types}


@op("export.minimal.apply")
def export_minimal_apply(ctx: Ctx, spec: dict) -> dict:
    import ida_auto

    from .. import edits

    for t in spec.get("types", []):
        edits.HANDLERS["local_type"].set(None, "", t, {})
    for f in spec.get("functions", []):
        ida_funcs.add_func(f["start"], f["end"])
    ida_auto.auto_wait()
    for f in spec.get("functions", []):
        ida_name.set_name(f["start"], f["name"], ida_name.SN_NOWARN | ida_name.SN_NOCHECK)
        if f.get("type"):
            try:
                typesupport.apply_decl(f["start"], f["type"])
            except IcliError:
                pass
    for n in spec.get("names", []):
        if n.get("name") and ida_segment.getseg(n["ea"]) is not None:
            ida_name.set_name(n["ea"], n["name"], ida_name.SN_NOWARN | ida_name.SN_NOCHECK)
    return {"_t": "minimal", "functions": len(spec.get("functions", []))}
